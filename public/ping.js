/* KsuNiMeet — метка адреса.
 *
 * ЗАЧЕМ. net.js выбирает, с какого адреса открывать приложение, и ему нужно
 * знать не «сервер отвечает», а «по этому адресу лежит ИМЕННО ЭТО приложение».
 * Разница не теоретическая: на своём же домене когда-то стояла другая версия
 * (PHP-сайт) — она тоже отвечает 200 на manifest.json. Перейти туда значило бы
 * показать человеку чужой интерфейс и потерять его вход.
 *
 * КАК. Каждая проба приходит со своим случайным token в адресе скрипта, и этот
 * файл возвращает ровно его. Угадать token нельзя, поэтому подделать ответ
 * чужой страницей тоже нельзя. Обычный <script> вместо fetch выбран нарочно:
 * ему не нужен Access-Control-Allow-Origin, значит зеркалу достаточно отдавать
 * файл — никакой настройки CORS.
 */
window.KSU_MIRROR_TAG = (function () {
  var s = document.currentScript;
  var m = s && s.src ? /[?&]token=([^&]+)/.exec(s.src) : null;
  return m ? decodeURIComponent(m[1]) : 'ksunimeet-web';
})();
