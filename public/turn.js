/* KsuNiMeet — TURN-ретранслятор для звонков и «Смотрим вместе».
 *
 * ЗАЧЕМ. Соединение строится напрямую (P2P), и на обычных домашних сетях
 * этого хватает: оба конца видят друг друга через STUN. Но если один из
 * собеседников за строгим NAT, мобильным оператором или VPN, прямого пути не
 * будет вовсе — и звонок просто не встанет. Тогда нужен TURN: он принимает
 * поток на себя и пересылает дальше. Пакеты уже зашифрованы собеседниками,
 * ретранслятор их не читает.
 *
 * ДВЕ ДОРОГИ — выберите одну (можно обе сразу, они сложатся).
 *
 * 1) Готовый бесплатный релей (быстрее всего, ничего не поднимать).
 *    Например Open Relay от Metered: 20 ГБ в месяц, порты 80 и 443, TURN
 *    поверх TLS, и он сам выбирает ближайший к собеседнику узел.
 *    Регистрация бесплатная, после неё вы получите ссылку вида
 *      https://<ваш-аккаунт>.metered.live/api/v1/turn/credentials?apiKey=<КЛЮЧ>
 *    и вписываете её сюда:
 *
 *      window.KSU_TURN_API = 'https://<аккаунт>.metered.live/api/v1/turn/credentials?apiKey=<КЛЮЧ>';
 *
 *    Проверено: с российских узлов (check-host, 3/3) этот хост отвечает —
 *    то есть это не Cloudflare, которого в России тормозят по 16 КБ на файл.
 *
 *    ВАЖНО ПРО КЛЮЧ: он уезжает в статический сайт, то есть виден любому,
 *    кто откроет исходники. Сам по себе это небольшой риск — эндпоинт
 *    выдаёт КОРОТКОЖИВУЩИЕ креды на пару часов, а не постоянные, — но
 *    чужой трафик съест ваши бесплатные 20 ГБ. Ключ можно сменить в любой
 *    момент в личном кабинете.
 *
 * 2) Свой релей (coturn на своём VPS) — без лимитов и посредников.
 *    Вписываете адреса напрямую:
 *
 *      window.KSU_TURN_SERVERS = [
 *        { urls: ['turns:ваш-сервер:443?transport=tcp'], username: '...', credential: '...' },
 *        { urls: ['turn:ваш-сервер:443?transport=tcp'],  username: '...', credential: '...' }
 *      ];
 *
 *    Порт 443 — самый живучий: он выглядит как обычный HTTPS и проходит там,
 *    где UDP закрыт наглухо. Для coturn включите use-auth-secret и отдавайте
 *    короткоживущие креды своим эндпоинтом через window.KSU_TURN_API — тогда
 *    постоянный секрет сервера в браузер не попадёт вообще.
 *
 * КАК ЭТО ЧИТАЮТ ЗВОНИЛКА И «СМОТРИМ ВМЕСТЕ». Они не берут список сразу, а
 * ждут window.KSU_TURN_READY (промис). Поэтому опрос за свежими кредами НЕ
 * задерживает звонок: у запроса есть свой бюджет (BUDGET), и по его истечении
 * соединение строится на том, что уже есть. Если ничего не настроено, промис
 * уже разрешён — ожидания нет ни на миллисекунду.
 */

window.KSU_TURN_SERVERS = window.KSU_TURN_SERVERS || [];
window.KSU_TURN_API = window.KSU_TURN_API || '';

(function () {
  'use strict';

  var STATIC = window.KSU_TURN_SERVERS.slice();
  var API = window.KSU_TURN_API || '';
  var BUDGET = 2500;   // мс: дольше ждать релей смысла нет — звонок важнее

  if (!API) {
    window.KSU_TURN_READY = Promise.resolve(STATIC);
    return;
  }

  window.KSU_TURN_READY = new Promise(function (resolve) {
    var done = false;
    function finish(extra) {
      if (done) return;            // первый ответ выигрывает, остальное игнорим
      done = true;
      resolve((extra || []).concat(STATIC));
    }
    setTimeout(function () { finish([]); }, BUDGET);
    try {
      fetch(API, { cache: 'no-store' })
        .then(function (r) { return r.ok ? r.json() : null; })
        .then(function (j) {
          if (!j) { finish([]); return; }
          // Сервисы возвращают либо массив сразу, либо {iceServers: [...]}.
          finish(Array.isArray(j) ? j : (j.iceServers || []));
        })
        .catch(function () { finish([]); });
    } catch (e) { finish([]); }
  });
})();
