/* Правка схемы: у `films.idx` снять обязательность.
 *
 * ЗАЧЕМ. У числового поля PocketBase «пусто» и «ноль» — одно и то же значение,
 * поэтому `required: true` отвергает 0 с ошибкой `validation_required`
 * («Cannot be blank»). Приложение нумерует части фильма С НУЛЯ, то есть первая
 * часть не залилась бы никогда — «Смотрим вместе» не заработало бы вообще.
 * Проверено на живом сервере: idx=1 проходит, idx=0 падает с 400.
 *
 * ПОЧЕМУ ОТДЕЛЬНОЙ МИГРАЦИЕЙ, А НЕ ПРАВКОЙ ПЕРВОЙ. Первая миграция уже стоит
 * на базе (её не перезапустить: PocketBase помечает применённые файлы и больше
 * к ним не возвращается), а `migrate down` требует ручного подтверждения и на
 * живой базе означал бы снос всех данных. Отдельный файл идемпотентен: на
 * свежей установке он ничего не меняет (поле уже необязательное), на
 * существующей — приводит её к тому же виду.
 *
 * Обязательность данных при этом не теряется: адаптер (public/pb.js) всегда
 * присылает idx, а от дублей защищает уникальный индекс (room, movie, idx).
 */

migrate(
  (app) => {
    const films = app.findCollectionByNameOrId("films");
    films.fields.getByName("idx").required = false;
    app.save(films);
  },
  (app) => {
    // Откат возвращает прежнее состояние — но помните, что с ним части с
    // номером 0 снова перестанут приниматься.
    const films = app.findCollectionByNameOrId("films");
    films.fields.getByName("idx").required = true;
    app.save(films);
  },
);
